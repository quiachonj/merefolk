import esbuild from "esbuild";
import process from "process";
import path from "path";
import { fileURLToPath } from "url";
import builtins from "builtin-modules";

const dirname = path.dirname(fileURLToPath(import.meta.url));

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, visit the plugin's github repository
*/`;

const prod = process.argv[2] === "production";

const context = await esbuild.context({
	banner: { js: banner },
	entryPoints: ["src/main.ts"],
	bundle: true,
	format: "cjs",
	target: "es2018",
	platform: "browser",
	// React/Excalidraw JSX -> React 18 automatic runtime.
	jsx: "automatic",
	// Excalidraw 0.18 ships conditional exports (prod/dev) and the CSS subpath
	// has no `default` condition, so we pin `production` to resolve both its JS
	// and its stylesheet. The stylesheet is imported in main.ts and bundled as a
	// string via the `.css -> text` loader, then injected at runtime (Obsidian
	// only auto-loads the plugin's own styles.css).
	conditions: ["production"],
	loader: { ".css": "text" },
	alias: {
		// Excalidraw only dynamically import()s this for its built-in Mermaid
		// dialog, which Merefolk never opens. Alias it to a tiny stub to drop
		// ~6 MB (cytoscape/katex) from the bundle. See src/stubs/.
		"@excalidraw/mermaid-to-excalidraw": path.resolve(
			dirname,
			"src/stubs/mermaid-to-excalidraw.ts",
		),
	},
	define: {
		"process.env.NODE_ENV": prod ? '"production"' : '"development"',
	},
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtins,
	],
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	minify: prod,
	logLevel: "info",
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
